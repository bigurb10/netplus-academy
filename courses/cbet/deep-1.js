u2l1: `## Water in pipes, and why the analogy works
Voltage is water pressure. Current is the flow of water. Resistance is how narrow the pipe is. Power is how much work the flowing water does, which for electricity mostly means heat. Push harder (more voltage) and more flows; narrow the pipe (more resistance) and less flows. That is Ohm's law, and it is the whole basis of every voltage and resistance measurement you will ever take.

## The law and its three forms
\`\`\`
        V
      -----      cover the one you want:   V = I x R      I = V / R      R = V / I
     I  x  R
\`\`\`
- 9 V battery across a 3 ohm lamp: I = 9 / 3 = 3 A.
- A heater draws 5 A from 120 V: R = 120 / 5 = 24 ohms.
- 2 A through a 50 ohm resistor: V = 2 x 50 = 100 V across it.

## Power: where the heat comes from
\`\`\`
P = V x I            120 V x 2 A = 240 W
P = I squared x R    (2 A) squared x 24 ohms = 96 W
P = V squared / R    (120 V) squared / 60 ohms = 240 W
\`\`\`
The squared forms matter for troubleshooting: double the current through a resistor and it dissipates four times the heat. That is why a slightly overloaded component browns and fails, and why a resistor rated for a quarter watt in a circuit that now carries more current than designed is the one you find scorched.

## Series: one path
\`\`\`
  +----[R1 = 6]----[R2 = 2]----+
  |                            |
 24 V                          |
  |                            |
  +----------------------------+
\`\`\`
There is only one path, so the **same current** flows through everything. Resistances add: 6 + 2 = 8 ohms. Current: 24 / 8 = 3 A. Voltage drops: 3 x 6 = 18 V across R1, 3 x 2 = 6 V across R2, and 18 + 6 = 24, the source. Voltages **add up** to the source. Open any component and everything stops, which is exactly what a fuse is for. A string of old Christmas lights was a series circuit, which is why one bulb killed the string.

## Parallel: several paths
\`\`\`
  +-----+-----+
  |     |     |
 12 V  [R1]  [R2]      R1 = 6 ohms, R2 = 3 ohms
  |     |     |
  +-----+-----+
\`\`\`
Every branch sees the **same voltage**, 12 V. Each draws its own current: 12/6 = 2 A and 12/3 = 4 A. Currents **add**: 6 A total. Total resistance is 12 / 6 = 2 ohms, smaller than the smallest branch, because adding a path always makes it easier for current to flow. The formula: 1 / R = 1/6 + 1/3 = 1/2, so R = 2. For two resistors, the shortcut (R1 x R2) / (R1 + R2) = 18 / 9 = 2. Wall outlets are parallel, so one dead device does not affect the others.

## Kirchhoff, without the algebra
- What flows into a junction flows out. If 6 A enters a node and 2 A leaves on one branch, 4 A leaves on the other.
- Go around any loop and the voltage rises equal the voltage drops. The 24 V source in the series example is matched by 18 + 6 of drops.
These are the rules you use silently when you compare a measured voltage to the one printed on a schematic and decide which stage is wrong.

## The shock connection
The body is a resistor, and Ohm's law decides how much current a voltage pushes through it.
\`\`\`
120 V through dry skin, about 100,000 ohms:   I = 120 / 100,000 = 1.2 mA     a tingle
120 V through wet skin, about 1,000 ohms:     I = 120 / 1,000 = 120 mA       fibrillation range
120 V through a catheter to the heart, ohms in the hundreds: amps enough to kill instantly
\`\`\`
Same voltage, three outcomes, because resistance changed. This is the whole reason wet locations, sweaty patients, and cardiac catheters get special rules.

## How the exam asks it
- "A 12 V supply drives 3 A through a load; what is the resistance?" 4 ohms.
- "Two 100 ohm resistors in parallel?" 50 ohms.
- "In a series circuit, which quantity is the same through every component?" Current.
- "A resistor's current doubles; its power dissipation..." Quadruples.

## What to memorize
- V = IR, P = VI = I squared R = V squared / R.
- Series: same current, voltages add, resistances add. Parallel: same voltage, currents add, resistance shrinks.
- Shock current = voltage / body resistance; wet skin is deadly at wall voltage.`,

